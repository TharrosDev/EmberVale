def build_celestial() -> tuple[str, list[str]]:
    spec = cells()
    issues = check_tiling("CelestialRealm", spec, ROWS, EXTENT_X)
    spec = place_world(spec, geography())
    spec, road_issues = realize_roads(spec, roads())
    issues += [f"CelestialRealm: {issue}" for issue in road_issues]
    issues += check_envelopes("CelestialRealm", spec, {c.key: list(c.routes) for c in spec})
    return emit("celestial", HEADER, spec, [], ENVIRONMENT, BUDGET, RESOURCE, SCATTER, "CelestialRuin"), issues


if __name__ == "__main__":
    _text, _issues = build_celestial()
    for _issue in _issues:
        print(f"LATTICE ERROR: {_issue}")
    print("self-check: FAILED" if _issues else f"self-check: builds ({len(_text)} bytes), lattice sound")
    raise SystemExit(1 if _issues else 0)
