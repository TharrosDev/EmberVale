def allocation(e):
    if e["id"] in ALLOC_OVERRIDE:
        alloc = ALLOC_OVERRIDE[e["id"]]
    elif e["slot"] == "Ammo":
        alloc = (("PhysicalPower", 1.0),)
    elif e["slot"] == "Ring":
        alloc = RING_ALLOC[e["tier"]]
    elif e["slot"] == "Amulet":
        alloc = (("R", 0.6), (AMULET_SECOND[e["tier"]], 0.4))
    elif e["weapon_class"] != "None":
        alloc = WEAPON_ALLOC[e["weapon_class"]]
    else:
        alloc = ARMOR_ALLOC[e["armor_weight"]]
    return tuple((realm_resist(e["tier"], e["armor_weight"]) if s == "R" else s, f) for s, f in alloc)


def snap(stat, value):
    step = STAT_STEP.get(stat, 1.0)
    return round(round(value / step) * step, 4)


def score(stats):
    return sum(STAT_WEIGHT[s] * v for s, v in stats.items())


def stat_block(e):
    """The stats an equippable carries: every secondary stat rounded to its grain, then the primary
    given whatever is left of the budget (at least one grain), so the total lands on the budget."""
    budget = budget_points(e["item_level"], e["slot"], e["two_handed"], e["rarity_floor"])
    alloc = allocation(e)
    stats = {}
    for stat, fraction in alloc[1:]:
        value = snap(stat, budget * fraction / STAT_WEIGHT[stat])
        if value > 0:
            stats[stat] = value
    primary = alloc[0][0]
    left = budget - score(stats)
    stats[primary] = max(STAT_STEP.get(primary, 1.0), snap(primary, left / STAT_WEIGHT[primary]))
    off = abs(score(stats) - budget)
    assert off <= max(BUDGET_TOLERANCE * budget, BUDGET_GRAIN), (e["id"], stats, budget)
    return stats


