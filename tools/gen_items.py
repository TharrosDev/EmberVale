def splice(text, script_file, array_prop, blocks):
    """Replaces every '<prefix>ics_*' sub resource of `text` with `blocks` ((id, body lines), ...)
    and rewrites the `array_prop` list to match. Everything else is left byte-for-byte alone."""
    ext = re.search(r'\[ext_resource type="Script" path="res://[^"]*/%s" id="([^"]+)"\]' % re.escape(script_file), text)
    if not ext and blocks:
        # A shop that stocked nothing has no entry script declared yet: declare it after the last ext.
        ids = re.findall(r'^\[ext_resource [^\]]*\]$', text, re.M)
        new_ext = '[ext_resource type="Script" path="res://src/Economy/%s" id="ics_entry"]' % script_file
        text = text.replace(ids[-1], ids[-1] + "\n" + new_ext, 1)
        ext = re.search(r'id="(ics_entry)"', text)
    text = re.sub(r'\[sub_resource type="Resource" id="[A-Za-z]+_%s[^"]*"\]\n(?:(?!\[)[^\n]+\n)*\n' % ICS, "", text)
    rendered = ""
    for sid, body in blocks:
        rendered += '[sub_resource type="Resource" id="%s"]\n' % sid
        rendered += 'script = ExtResource("%s")\n' % ext.group(1)
        rendered += "\n".join(body) + "\n\n"
    lines = text.split("\n")
    at = lines.index("[resource]")
    while at > 0 and lines[at - 1].startswith(";"):
        at -= 1
    text = "\n".join(lines[:at]) + ("\n" if at else "") + rendered + "\n".join(lines[at:])

    def relist(match):
        kept = [x for x in match.group(2).split(", ") if x and ("_" + ICS) not in x]
        kept += ['SubResource("%s")' % sid for sid, _ in blocks]
        return match.group(1) + ", ".join(kept) + match.group(3)

    text, count = re.subn(r"^(%s = Array\[Resource\]\(\[)(.*)(\]\))$" % array_prop, relist, text, flags=re.M)
    assert count == 1, "no %s list to splice into" % array_prop
    steps = len(re.findall(r"^\[(?:ext|sub)_resource ", text, re.M)) + 1
    return re.sub(r"load_steps=\d+", "load_steps=%d" % steps, text, count=1)


def shop_blocks(rows):
    blocks = []
    for item_id, quantity, lock in rows:
        assert item_id in C.ITEMS_BY_ID, "SHOP_STOCK names %s, which the catalogue does not plan" % item_id
        body = ["ItemId = %s" % quote(item_id), "Quantity = %d" % quantity]
        if "tier" in lock:
            body.append("RequiredTier = %d" % REPUTATION.index(lock["tier"]))
        if "flag" in lock:
            body.append("RequiredFlagId = %s" % quote(lock["flag"]))
        if "invest" in lock:
            body.append("RequiredInvestment = %d" % lock["invest"])
        blocks.append(("Stock_%s%d" % (ICS, len(blocks) + 1), body))
    return blocks


def pool_blocks(rows):
    return [("Entry_%s%d" % (ICS, i + 1),
             ["ItemId = %s" % quote(item_id), "DropChance = %s" % fnum(chance), "MinQuantity = 1", "MaxQuantity = 1",
              "RollAffixes = %s" % ("true" if roll else "false")])
            for i, (item_id, chance, roll) in enumerate(rows)]


def new_pool_text():
    return "\n".join([
        '[gd_resource type="Resource" script_class="LootTable" format=3]', "",
        '[ext_resource type="Script" path="res://src/Loot/LootTable.cs" id="1_table"]',
        '[ext_resource type="Script" path="res://src/Loot/LootEntry.cs" id="2_entry"]', "",
        POOL_HEADER, "", "[resource]", 'script = ExtResource("1_table")', "Entries = Array[Resource]([])",
        'GoldItemId = "item.currency.gold"', "GoldChance = 0.0", "GoldMin = 0", "GoldMax = 0", "QualityBonus = 0.0", ""])


RETROFIT_KEYS = ("ItemLevel", "Tier", "TwoHanded", "WeaponClass", "ArmorWeight")


def retrofit(text, fields):
    """Stamps the classification fields onto an existing item, appended to its [resource] section."""
    lines = [l for l in text.rstrip("\n").split("\n") if l.split(" = ")[0] not in RETROFIT_KEYS]
    lines += ["ItemLevel = %d" % fields["item_level"], "Tier = %d" % fields["tier"]]
    if fields["two_handed"]:
        lines.append("TwoHanded = true")
    if fields["weapon_class"] != "None":
        lines.append("WeaponClass = %d" % CLASSES.index(fields["weapon_class"]))
    if fields["armor_weight"] != "None":
        lines.append("ArmorWeight = %d" % WEIGHTS.index(fields["armor_weight"]))
    return "\n".join(lines) + "\n"


