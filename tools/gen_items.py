def budget_points(item_level, slot, two_handed, rarity):
    """The stat points an equippable of this level, slot and rarity spends.

    A chest piece gets 6 + 0.9 per item level (10.5 at level 5, 48.3 at level 47); every other slot
    a share of that; rarity scales it. With the armour allocations below, a full heavy suit and
    shield reaches about 185 Armor at item level 47, a medium suit about 120 and a light one about
    70, on the 100 / (100 + armour) curve the damage pipeline already uses.
    """
    share = SLOT_SHARE[slot] * (TWO_HANDED_SHARE if two_handed else 1.0)
    return (6.0 + 0.9 * item_level) * share * RARITY_FACTOR[rarity]


#: Sword-equivalent damage multiplier per weapon class (WeaponResource.BaseDamage).
CLASS_DAMAGE = {
    "Sword": 1.0, "Dagger": 0.72, "Axe": 1.12, "Mace": 1.08, "Spear": 0.95,
    "Staff": 0.8, "Greatsword": 1.6, "Bow": 1.12,
}


def weapon_damage(item_level, weapon_class, rarity):
    """WeaponResource.BaseDamage: 12 + 0.62 per item level for a sword (the Steel Sword's 20 at
    level 14), times the class multiplier, plus 4% per rarity step above Common."""
    return (12.0 + 0.62 * item_level) * CLASS_DAMAGE[weapon_class] * (1.0 + 0.04 * RARITIES.index(rarity))


VALUE_RARITY = {"Common": 1.0, "Uncommon": 1.25, "Rare": 1.8, "Epic": 2.6, "Legendary": 4.0}
VALUE_SLOT = {
    "Chest": 1.0, "Legs": 0.8, "Head": 0.7, "Hands": 0.55, "Feet": 0.55,
    "MainHand": 1.0, "OffHand": 0.8, "Ring": 0.9, "Amulet": 1.0, "Ammo": 0.04,
}


def item_value(item_level, rarity, slot):
    """ItemResource.Value of an equippable, in gold, from item level, rarity and slot alone.

    18 + 3.2 L + 0.06 L^2 is fitted to what main already sells (Iron Dagger 35 at level 5, Steel
    Sword 85 at 14, Drakescale Mail 420 at 28 Epic) and tops out near 1,300 for a level-50
    legendary: dear beside a 500-gold mercenary, never beyond what a late purse can reach. Above
    100 it rounds to the nearest 5.
    """
    raw = (18.0 + 3.2 * item_level + 0.06 * item_level * item_level) * VALUE_RARITY[rarity] * VALUE_SLOT[slot]
    if raw >= 100.0:
        return int(round(raw / 5.0)) * 5
    return max(1, int(round(raw)))


