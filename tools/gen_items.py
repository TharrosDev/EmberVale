def unique_tres(fx):
    lines = ["Id = %s" % quote(fx["id"]), "NameKey = %s" % quote(fx["name_key"]),
             "DescriptionKey = %s" % quote(fx["description_key"]), "Kind = %d" % UNIQUE_KINDS.index(fx["kind"])]
    for field, key in (("Magnitude", "magnitude"), ("Chance", "chance"), ("Threshold", "threshold"),
                       ("DurationSeconds", "duration"), ("CooldownSeconds", "cooldown")):
        if fx[key] != (1.0 if key == "chance" else 0.0):
            lines.append("%s = %s" % (field, fnum(fx[key])))
    if fx["status_id"]:
        lines.append("StatusId = %s" % quote(fx["status_id"]))
    return resource_text("UniqueEffectResource", "res://src/Items/UniqueEffectResource.cs", [], [], lines)


def set_tres(s):
    subs = []
    for pieces, stat, value, mod, effect in s["bonuses"]:
        body = ['script = ExtResource("2_bonus")', "PiecesRequired = %d" % pieces]
        if stat:
            body += ["Stat = %d" % STATS.index(stat), "Value = %s" % fnum(value), "ModifierType = %d" % MODS.index(mod)]
        if effect:
            body.append("EffectId = %s" % quote(effect))
        subs.append(("Bonus_%d" % (len(subs) + 1), body))
    ext = ['[ext_resource type="Script" path="res://src/Items/ItemSetBonusResource.cs" id="2_bonus"]']
    lines = ["Id = %s" % quote(s["id"]), "DisplayNameKey = %s" % quote(s["display_name_key"]),
             "PieceIds = %s" % strings(s["pieces"]),
             'Bonuses = Array[ExtResource("2_bonus")]([%s])' % ", ".join('SubResource("%s")' % sid for sid, _ in subs)]
    return resource_text("ItemSetResource", "res://src/Items/ItemSetResource.cs", ext, subs, lines)


def unique_description(fx):
    """The tooltip line with the effect's own numbers baked in, so a retune cannot leave a stale one."""
    flat = fx["kind"] in ("DodgeRefund", "ThornsFlat")
    magnitude = num(fx["magnitude"]) if flat else num(fx["magnitude"] * 100) + "%"
    return fx["desc"].format(magnitude, num(fx["chance"] * 100) + "%", num(fx["threshold"] * 100) + "%",
                             num(fx["duration"]), num(fx["cooldown"]))


