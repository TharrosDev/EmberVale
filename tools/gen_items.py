def read(path):
    return io.open(path, encoding="utf-8", newline="").read() if os.path.exists(path) else None


def existing_item_files():
    """id -> path of every hand-authored item (anything in data/items without the marker)."""
    found = {}
    for name in sorted(os.listdir(ITEM_DIR)):
        if name.endswith(".tres"):
            text = read(os.path.join(ITEM_DIR, name))
            if GENERATED not in text:
                found[re.search(r'^Id = "([^"]+)"', text, re.M).group(1)] = os.path.join(ITEM_DIR, name)
    return found


def build():
    problems = C.validate()
    assert not problems, problems
    wanted = {}   # path -> full text of a file this generator owns outright
    edited = {}   # path -> new text of a hand-authored file it splices into
    hand = existing_item_files()

    for e in C.ITEMS:
        path = os.path.join(ITEM_DIR, file_stem(e["id"]) + ".tres")
        assert path not in hand.values() and path not in wanted, "file name collision: " + path
        if e["kind"] == "equippable":
            wanted[path] = equippable_tres(e, stat_block(e))
            if e["slot"] == "MainHand":
                wanted[os.path.join(WEAPON_DIR, "Player%s.tres" % file_stem(e["id"]))] = weapon_tres(e)
        elif e["kind"] == "consumable":
            wanted[path] = consumable_tres(e)
        else:
            wanted[path] = plain_tres(e)

    for fx in C.UNIQUE_EFFECTS:
        wanted[os.path.join(UNIQUE_DIR, pascal(fx["id"].split(".", 1)[1]) + ".tres")] = unique_tres(fx)
    for s in C.SETS:
        wanted[os.path.join(SET_DIR, pascal(s["id"].split(".", 1)[1]) + ".tres")] = set_tres(s)

    for item_id, fields in C.EXISTING_RETROFIT.items():
        edited[hand[item_id]] = retrofit(read(hand[item_id]), fields)

    for name, rows in SHOP_STOCK.items():
        path = os.path.join(SHOP_DIR, name + ".tres")
        edited[path] = splice(read(path), "ShopStockEntry.cs", "Stock", shop_blocks(rows))
    for name in POOLS:
        path = os.path.join(LOOT_DIR, name + ".tres")
        edited[path] = splice(read(path) or new_pool_text(), "LootEntry.cs", "Entries", pool_blocks(pool_entries(name)))

    edited[CSV] = build_locale(read(CSV))
    edited[VALIDATOR] = build_validator(read(VALIDATOR))
    return wanted, edited


def stale_files(wanted):
    """Marked files the catalogue no longer names. Unmarked (hand-authored) files are never listed."""
    stale = []
    for folder in (ITEM_DIR, WEAPON_DIR, UNIQUE_DIR, SET_DIR):
        if not os.path.isdir(folder):
            continue
        for name in sorted(os.listdir(folder)):
            full = os.path.join(folder, name)
            if name.endswith(".tres") and full not in wanted and GENERATED in read(full):
                stale.append(full)
    return stale


def main():
    check = "--check" in sys.argv
    wanted, edited = build()
    changed = []
    for path, text in list(wanted.items()) + list(edited.items()):
        if read(path) != text:
            changed.append(path)
            if not check:
                if not os.path.isdir(os.path.dirname(path)):
                    os.makedirs(os.path.dirname(path))
                io.open(path, "w", encoding="utf-8", newline="").write(text)
    for path in stale_files(wanted):
        changed.append(path)
        if not check:
            os.remove(path)

    summary = "%d items (%d equippable, %d consumable, %d material, %d scroll), %d sets, %d unique effects" % (
        len(C.ITEMS), len(C.EQUIPPABLES), len(C.CONSUMABLES), len(C.NEW_MATERIALS), len(C.RECIPE_SCROLLS),
        len(C.SETS), len(C.UNIQUE_EFFECTS))
    if check:
        for c in changed:
            print("WOULD CHANGE", os.path.relpath(c, ROOT))
        print("%s; %d file(s) out of date" % (summary, len(changed)))
        return 1 if changed else 0
    print("%s; wrote %d file(s)" % (summary, len(changed)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
