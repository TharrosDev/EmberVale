# The three shop gear pools, rolled at each restock (ShopStockService). Each grid item of the named
# tiers gets an entry at GRID_CHANCE; drop-sourced set pieces and the one drop legendary ride along
# as rare finds, unrolled (RollAffixes false keeps the template's own rarity).
POOLS = {
    "ShopLeveledGear": {"tiers": (1,), "grid": 0.07, "sets": 0.0},
    "TravellerLeveledGear": {"tiers": (2, 3), "grid": 0.045, "sets": 0.012},
    "EmbermarketCaravanGear": {"tiers": (4, 5, 6), "grid": 0.025, "sets": 0.012},
}
POOL_HEADER = """; Hesk's rolled shelf (ics): the wares of the two realms a wayfarer actually walks, the Reach and the
; Ashen Wilds. Entries are generated by tools/gen_items.py from tools/items/catalogue.py; the pool is
; non-stackable gear only, with no gold, for the reasons ShopLeveledGear.tres gives."""


def pool_entries(name):
    spec = POOLS[name]
    rows = []
    for e in C.EQUIPPABLES:
        if e["tier"] not in spec["tiers"] or e["slot"] == "Ammo":
            continue
        named = bool(e["set_id"] or e["unique_effect_id"])
        if not named:
            rows.append((e["id"], spec["grid"], True))
        elif e["source"] == "drop" and spec["sets"] > 0:
            rows.append((e["id"], spec["sets"], False))
    if name == "TravellerLeveledGear":  # tier-1 set pieces have no tier-1 pool that carries rare finds
        rows += [(e["id"], spec["sets"], False) for e in C.EQUIPPABLES if e["set_id"] == "set.emberguard"]
    return rows


