def csv_cell(text):
    return '"%s"' % text.replace('"', '""') if any(c in text for c in ',"\n') else text


def build_locale(existing):
    lines = [MARK_BEGIN,
             "# Item sets and unique effects. Generated by tools/gen_items.py from tools/items/catalogue.py."]
    for s in C.SETS:
        lines.append("%s,%s" % (s["display_name_key"], csv_cell(s["name"][:-2] if s["name"].endswith("'s") else s["name"])))
    for fx in C.UNIQUE_EFFECTS:
        lines.append("%s,%s" % (fx["name_key"], csv_cell(fx["name"])))
        lines.append("%s,%s" % (fx["description_key"], csv_cell(unique_description(fx))))
    lines.append(MARK_END)
    sep = "\r\n" if "\r\n" in existing else "\n"  # strings.csv is CRLF; an LF block would never settle
    assert MARK_BEGIN in existing, "strings.csv has no ics:content block"
    return re.sub(re.escape(MARK_BEGIN) + r".*?" + re.escape(MARK_END), lambda _: sep.join(lines), existing, flags=re.S)


def cs_list(name, summary, values):
    out = ["    /// <summary>%s</summary>" % summary,
           "    public static readonly IReadOnlyList<string> %s = new[]" % name, "    {"]
    out += ['        "%s",' % v for v in values]
    out.append("    };")
    return out


def build_validator(existing):
    lines = [CS_BEGIN]
    lines += cs_list("ItemIds", "Every item tools/items/catalogue.py plans, in catalogue order.", [e["id"] for e in C.ITEMS])
    lines.append("")
    lines += cs_list("SetIds", "Every planned item set.", C.SET_IDS)
    lines.append("")
    lines += cs_list("UniqueEffectIds", "Every planned unique effect.", C.UNIQUE_EFFECT_IDS)
    lines.append("")
    lines += cs_list("BossSignatureIds", "The legendary each Flamebearer drops; boss-owned, so nothing sells them.",
                     sorted(C.BOSS_SIGNATURE.values()))
    lines.append(CS_END)
    assert CS_BEGIN in existing, "ItemValidator.Content.cs has no generated block"
    # C# is checked out with the platform's endings (autocrlf), so the block follows the file's.
    sep = "\r\n" if "\r\n" in existing else "\n"
    return re.sub(re.escape(CS_BEGIN) + r".*?" + re.escape(CS_END), lambda _: sep.join(lines), existing, flags=re.S)


