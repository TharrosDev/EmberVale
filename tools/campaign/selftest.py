@check
def patcher_on_a_copy():
    original = pristine("WarbandHeart")
    patch = Patch("quest.warband.heart",
                  append=[interact("interact.arena_gate", K("quest.warband.heart.obj_arena"), tag="arena",
                                   location="location.frostfang.arena"),
                          reach("location.frostfang.arena", K("quest.warband.heart.obj_reach"), tag="reach", optional=True)],
                  auto_start="flag.main.bounty_done", start_flag="flag.main.heart_started",
                  fields={"ChapterKey": "chapter.act1"})
    out = tres.apply_patch(original, patch)
    assert tres.apply_patch(out, patch) == out, "idempotent"
    # every original line survives; the only edited line is the Objectives array
    import difflib
    removed = [ln[2:] for ln in difflib.ndiff(original.splitlines(), out.splitlines()) if ln.startswith("- ")]
    assert removed == ['Objectives = Array[Resource]([SubResource("Obj_kill")])'], removed
    for needle in ('CompletionFlagId = "flag.frostfang.passage_open"', 'Description = "quest.warband.heart.obj"'):
        assert out.count(needle) == 1, needle
    secs = tres.parse(out)
    res = tres.resource_of(secs)
    assert res.props["Objectives"] == ["Obj_kill", "Obj_arena", "Obj_reach"], res.props["Objectives"]
    assert res.props["AutoStartFlagId"] == "flag.main.bounty_done" and res.props["StartFlagId"] == "flag.main.heart_started"
    assert res.props["ChapterKey"] == "chapter.act1" and res.props["CompletionFlagId"] == "flag.frostfang.passage_open"
    assert tres.sub_index(secs)["Obj_reach"].props["IsOptional"] is True
    assert tres.sub_index(secs)["Obj_kill"].props["TargetId"] == "enemy.goblin"
    # a flag that is already set to something else is never overwritten
    try:
        tres.apply_patch(original, Patch("quest.warband.heart", completion_flag="flag.other"))
        raise AssertionError("overwrote a set field")
    except tres.PatchError:
        pass
    try:
        tres.apply_patch(original, Patch("quest.warband.bounty"))
        raise AssertionError("patched the wrong quest")
    except tres.PatchError:
        pass
    # an empty field is filled in place; load_steps follows added sub-resources; CRLF is preserved
    synthetic = ('[gd_resource type="Resource" script_class="QuestResource" load_steps=4 format=3]\r\n\r\n'
                 '[ext_resource type="Script" path="res://src/Quests/ObjectiveResource.cs" id="2_obj"]\r\n\r\n'
                 '[sub_resource type="Resource" id="Obj_a"]\r\nscript = ExtResource("2_obj")\r\nType = 0\r\n\r\n'
                 '[resource]\r\nId = "quest.t.t"\r\nObjectives = Array[Resource]([SubResource("Obj_a")])\r\n'
                 'AutoStartFlagId = ""\r\n')
    out2 = tres.apply_patch(synthetic, Patch("quest.t.t", append=[talk("dialogue.d", K("a.b"), tag="x")],
                                             auto_start="flag.go"))
    assert "load_steps=5" in out2 and 'AutoStartFlagId = "flag.go"' in out2 and out2.count("AutoStartFlagId") == 1
    assert "\r\n" in out2 and re.search(r"(?<!\r)\n", out2) is None
    # lowering: appended objectives need a tag unless their text is a K
    try:
        locale.lower([], [Patch("quest.t.t", append=[talk("dialogue.d", "prose")])], [])
        raise AssertionError("untagged prose accepted")
    except ValueError:
        pass
    _, lp, _, rows = locale.lower([], [Patch("quest.warband.heart", append=[interact("i.x", "Open it", tag="gate")])], [])
    assert rows == [("quest.warband.heart.obj_gate", "Open it")] and lp[0].append[0].text == "quest.warband.heart.obj_gate"


