BASE_CSV = ("keys,en\r\n# comment\r\na.b,Hello\r\n# --- BEGIN campaign:one ---\r\n# --- END campaign:one ---\r\n"
            "c.d,\"Quoted, text\"\r\n# --- BEGIN campaign:two ---\r\nold.row,stale\r\n# --- END campaign:two ---\r\n")


@check
def locale_block_rewrite():
    rows = [("x.one", "plain"), ("x.two", 'has, comma and "quotes"'), ("x.three", " padded ")]
    t1 = locale.rewrite_block(BASE_CSV, "one", rows)
    assert locale.rewrite_block(t1, "one", rows) == t1, "idempotent"
    assert "\r\n" in t1 and "\n" not in t1.replace("\r\n", ""), "CRLF preserved"
    assert 'x.two,"has, comma and ""quotes"""' in t1 and 'x.three," padded "' in t1 and "x.one,plain" in t1
    # only the one block changed
    assert t1.replace("x.one,plain\r\n", "").split("# --- END campaign:one ---")[1] == BASE_CSV.split("# --- END campaign:one ---")[1]
    t2 = locale.rewrite_block(t1, "two", [])
    assert "old.row" not in t2 and "x.one,plain" in t2
    assert locale.rewrite_block(t2, "one", []) != t2 and "x.one" not in locale.rewrite_block(t2, "one", [])
    # a missing block is appended only when it has rows, and the LF style is kept
    lf = "keys,en\na,b\n"
    assert locale.rewrite_block(lf, "new", []) == lf
    added = locale.rewrite_block(lf, "new", [("k.v", "w")])
    assert added == "keys,en\na,b\n# --- BEGIN campaign:new ---\nk.v,w\n# --- END campaign:new ---\n", repr(added)
    # round trip through the csv reader
    assert dict((r[0], r[1]) for r in locale.parse_rows(t1))["x.two"] == 'has, comma and "quotes"'
    assert locale.fmt_row("k", "Truth") == "k,Truth"


