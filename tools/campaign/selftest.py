def mini_graph() -> dict:
    def quest(qid, auto="", done="", prereq="", main=True, reads=(), writes=(), objectives=()):
        return {"id": qid, "autoStart": auto, "completionFlag": done, "prerequisite": prereq, "isMain": main,
                "objectives": list(objectives),
                "reads": [{"flag": f, "via": v} for f, v in ([(auto, "autoStart")] if auto else []) + list(reads)],
                "writes": ([{"flag": done, "via": "completion"}] if done else []) + [{"flag": f, "via": v} for f, v in writes],
                "source": "generated"}
    quests = [
        quest("quest.a", auto="flag.boss", done="flag.a_done", writes=[("flag.fork.x", "objective[0].completion")]),
        quest("quest.b", auto="flag.a_done", done="flag.b_done", reads=[("flag.fork.x", "objective[1].required")]),
        quest("quest.c", auto="flag.b_done", done="flag.c_done", reads=[("flag.later", "objective[0].required")]),
        quest("quest.d", auto="flag.nobody_sets"),
        quest("quest.e", auto="flag.c_done", done="flag.e_done", writes=[("flag.later", "objective[0].completion")]),
    ]
    flags = {}
    for q in quests:
        for w in q["writes"]:
            flags.setdefault(w["flag"], {"writers": [], "readers": [], "externalRefs": []})["writers"].append(
                {"kind": "quest", "id": q["id"], "via": w["via"]})
        for r in q["reads"]:
            flags.setdefault(r["flag"], {"writers": [], "readers": [], "externalRefs": []})["readers"].append(
                {"kind": "quest", "id": q["id"], "via": r["via"]})
    return {"codeFlags": ["flag.boss"], "terminalFlags": [], "entryQuests": [], "quests": quests,
            "dialogues": [], "flags": flags, "forks": []}


@check
def graph_analyses():
    g = mini_graph()
    assert graph.reachable(g) == {"quest.a", "quest.b", "quest.c", "quest.e"}, graph.reachable(g)
    anc = graph.ancestors(g)
    assert anc["quest.c"] == {"quest.a", "quest.b"} and anc["quest.a"] == set()
    scope = {q["id"] for q in g["quests"]}
    bad = graph.unordered_reads(g, scope)
    assert len(bad) == 2 and "quest.c reads flag.later" in bad[0] and "quest.d reads flag.nobody_sets" in bad[1], bad
    # flag.later is written by quest.e, which runs AFTER c; flag.nobody_sets has no writer at all
    assert graph.dead_end_flags(g, scope) == ["quest.e sets flag.e_done but nothing reads it (chain gap; add the next link or list it in TERMINAL_FLAGS)"]
    g["terminalFlags"] = ["flag.e_done"]
    assert graph.dead_end_flags(g, scope) == []


