        for name, age in (("cell1.scn", 0), ("cell2.scn", 3)):
            path = self.root / "cells" / "a" / name
            path.write_text("new")
            os.utime(path, (started + age, started + age))
        snapshot = world_bake.progress(expected, started, started + 10, fallback_rate=2.0)
