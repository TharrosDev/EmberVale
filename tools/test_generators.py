class ContentDiffTests(unittest.TestCase):
    def test_field_level_diff_names_root_and_sub_resource_fields(self):
        old = '[sub_resource type="Resource" id="Entry_a"]\nDropChance = 0.5\n[resource]\nId = "x.y"\nHealth = 80.0\nGone = 1\n'
        new = '[sub_resource type="Resource" id="Entry_a"]\nDropChance = 0.7\n[resource]\nId = "x.y"\nHealth = 95.0\nAdded = "v"\n'
        fields = {f["field"]: (f["old"], f["new"]) for f in content.diff_documents(old, new)["fields"]}
        self.assertEqual(fields, {"Health": ("80", "95"), "Entry_a.DropChance": ("0.5", "0.7"),
                                  "Gone": ("1", None), "Added": (None, "v")})

    def test_comment_and_line_ending_changes_are_not_content_changes(self):
        old = '[resource]\nId = "x.y"\n'
        self.assertEqual(content.diff_documents(old, "; note\r\n" + old.replace("\n", "\r\n"))["fields"], [])

    def test_locale_diff_counts_keys(self):
        self.assertEqual(content.diff_locale("a,1\nb,2\n# c\n", "a,1\nb,3\nd,4\n"),
                         {"added": 1, "removed": 0, "changed": 1})

    def test_fact_lines_collapse_wide_changes(self):
        fact = {"status": "~", "kind": "enemies", "path": "p", "id": "enemy.x",
                "fields": [{"field": f"Zone_{i}.Radius", "old": "1", "new": "2"} for i in range(8)]}
        self.assertEqual(content.fact_line(fact, False),
                         "~ enemy.x (enemies) 8 fields in 8 section(s): Zone_0, Zone_1, Zone_2 ...")
        self.assertIn("Zone_7.Radius 1 -> 2", content.fact_line(fact, True))
        self.assertEqual(content.summary_line({"items": {"+": 2, "~": 1}, "quests": {"-": 1}}),
                         "summary items +2 ~1 | quests -1")

    def test_diff_against_head_runs_on_this_repo(self):
        result = content.content_diff("HEAD", "HEAD")
        self.assertEqual(result["facts"], [])


