class RegenTests(unittest.TestCase):
    def setUp(self):
        self.temp = tempfile.TemporaryDirectory()
        self.root = Path(self.temp.name)
        (self.root / "out").mkdir()
        (self.root / "gen.py").write_text("# generator\n", encoding="utf-8")
        (self.root / "out" / "a.txt").write_text("old\n", encoding="utf-8")
        self.state = self.root / "artifacts" / "regen"
        self.entry = regen.Entry("gen", "test", ("gen.py", "--check"), ("gen.py",), ("gen.py", "out/*.txt"))
        regen._GLOBS.clear()

    def tearDown(self):
        self.temp.cleanup()

    def test_registry_keeps_the_catalogue_chain_in_order(self):
        names = [entry.name for entry in regen.REGISTRY]
        self.assertEqual(len(names), len(set(names)))
        chain = [names.index(n) for n in ("catalogue", "gen_items", "gen_recipes", "gen_loot")]
        self.assertEqual(chain, sorted(chain))
        for entry in regen.REGISTRY:
            for command in (entry.check, entry.write):
                if command:
                    self.assertTrue((ROOT / command[0]).is_file(), f"{entry.name}: {command[0]} does not exist")
            if entry.check is None:
                self.assertTrue(entry.owns, f"{entry.name} has no --check, so it must name the files it owns")
            self.assertTrue(regen.files_for(ROOT, entry.watch), f"{entry.name} watches nothing that exists")

    def test_classify(self):
        self.assertEqual(regen.classify(0, "", False, False), "ok")
        self.assertEqual(regen.classify(1, "WOULD CHANGE x", False, False), "DRIFT")
        self.assertEqual(regen.classify(2, "lattice error", False, False), "FAIL")
        self.assertEqual(regen.classify(1, "selftest: 10/11", False, True), "FAIL")
        self.assertEqual(regen.classify(1, "Traceback (most recent call last):\n", False, False), "ERROR")
        self.assertEqual(regen.classify(124, "", True, False), "ERROR")
        self.assertEqual(regen.first_reason("warning: differs a bit\n27 quests\nDRIFT: data/x: differs\ndone"),
                         "DRIFT: data/x: differs")

    def test_select_keeps_registry_order_and_rejects_unknown_names(self):
        self.assertEqual([e.name for e in regen.select(["gen_loot", "gen_items"])], ["gen_items", "gen_loot"])
        with self.assertRaises(SystemExit):
            regen.select(["nope"])

    def test_passing_check_is_cached_until_a_watched_file_changes(self):
        calls = []

        def run(root, arguments, timeout):
            calls.append(arguments)
            return process()
        first = regen.regen("check", [self.entry], self.root, self.state, run=run)
        second = regen.regen("check", [self.entry], self.root, self.state, run=run)
        self.assertEqual((first["exit_code"], second["cached"], len(calls)), (0, 1, 1))
        (self.root / "out" / "a.txt").write_text("hand edited\n", encoding="utf-8")
        regen._GLOBS.clear()
        self.assertEqual(regen.regen("stale", [self.entry], self.root, self.state, run=run)["drift"], ["gen"])
        regen.regen("check", [self.entry], self.root, self.state, run=run)
        self.assertEqual(len(calls), 2)
        regen.regen("check", [self.entry], self.root, self.state, use_cache=False, run=run)
        self.assertEqual(len(calls), 3)

    def test_line_endings_do_not_change_a_signature(self):
        before = regen.signature(self.root, self.entry)
        (self.root / "out" / "a.txt").write_bytes(b"old\r\n")
        regen._GLOBS.clear()
        self.assertEqual(regen.signature(self.root, self.entry), before)

    def test_drift_is_exit_1_and_a_crash_is_exit_2(self):
        drift = regen.regen("check", [self.entry], self.root, self.state,
                            run=lambda *a: process(1, "WOULD CHANGE out/a.txt"))
        self.assertEqual((drift["exit_code"], drift["drift"]), (1, ["gen"]))
        self.assertEqual((self.state / "gen.log").read_text(encoding="utf-8"), "WOULD CHANGE out/a.txt")
        crash = regen.regen("check", [self.entry], self.root, self.state,
                            run=lambda *a: process(1, "Traceback (most recent call last):\nboom"))
        self.assertEqual((crash["exit_code"], crash["errors"]), (2, ["gen"]))

    def test_fix_writes_what_drifted_then_proves_a_fixed_point(self):
        target = self.root / "out" / "a.txt"

        def run(root, arguments, timeout):
            if "--check" in arguments:
                return process(0 if target.read_text(encoding="utf-8") == "new\n" else 1, "WOULD CHANGE out/a.txt")
            target.write_text("new\n", encoding="utf-8")
            return process()
        result = regen.regen("fix", [self.entry], self.root, self.state, run=run)
        self.assertEqual((result["exit_code"], result["fixed"]), (0, ["gen"]))
        self.assertEqual(result["entries"][0]["changed"], ["out/a.txt"])

    def test_fix_reports_a_writer_that_never_settles(self):
        def run(root, arguments, timeout):
            if "--check" in arguments:
                return process(1, "WOULD CHANGE out/a.txt")
            (self.root / "out" / "a.txt").write_text(str(time.monotonic_ns()), encoding="utf-8")
            return process()
        result = regen.regen("fix", [self.entry], self.root, self.state, run=run)
        self.assertEqual((result["exit_code"], result["not_idempotent"]), (1, ["gen"]))
        self.assertEqual(result["entries"][0]["status"], "NOT-IDEMPOTENT")

    def test_writer_without_check_runs_on_a_copy_and_never_writes_the_tree(self):
        entry = regen.Entry("plain", "test", None, ("gen.py",), ("gen.py", "out/*.txt"), owns=("out/*.txt",),
                            reads=("in/*.txt",))
        (self.root / "in").mkdir()
        (self.root / "in" / "source.txt").write_text("input\n", encoding="utf-8")
        seen = {}

        def run(root, arguments, timeout):
            self.assertNotEqual(root, self.root)
            # The copy holds the script, what it reads and what it owns, at the same relative paths.
            seen["files"] = sorted(path.relative_to(root).as_posix() for path in root.rglob("*") if path.is_file())
            (root / "out" / "a.txt").write_text("regenerated\n", encoding="utf-8")
            (root / "out" / "b.txt").write_text("brand new\n", encoding="utf-8")
            # A run killed here leaves the real tree exactly as it was.
            self.assertEqual((self.root / "out" / "a.txt").read_text(encoding="utf-8"), "old\n")
            self.assertFalse((self.root / "out" / "b.txt").exists())
            return process()
        row = regen.run_check(self.root, entry, run)
        self.assertEqual(seen["files"], ["gen.py", "in/source.txt", "out/a.txt"])
        self.assertEqual((row["status"], row["changed"]), ("DRIFT", ["out/a.txt", "out/b.txt"]))
        self.assertEqual((self.root / "out" / "a.txt").read_text(encoding="utf-8"), "old\n")
        self.assertFalse((self.root / "out" / "b.txt").exists())
        self.assertEqual(regen.run_check(self.root, entry, lambda *a: process())["status"], "ok")

    def test_every_check_less_writer_finds_its_root_from_its_own_file(self):
        # run_in_copy relies on it: a writer that used the working directory or a fixed path
        # would write the real tree from inside the copy.
        for entry in regen.REGISTRY:
            if entry.check is None:
                text = (regen.ROOT / entry.write[0]).read_text(encoding="utf-8")
                self.assertIn("os.path.dirname(os.path.dirname(os.path.abspath(__file__)))", text, entry.name)
                for pattern in (*entry.owns, *entry.reads):
                    self.assertTrue(regen.files_for(regen.ROOT, (pattern,)), f"{entry.name}: {pattern} matches nothing")

    def test_an_imported_helper_invalidates_the_cache(self):
        (self.root / "tools").mkdir()
        (self.root / "tools" / "helper.py").write_text("X = 1\n", encoding="utf-8")
        (self.root / "tools" / "deep.py").write_text("Y = 1\n", encoding="utf-8")
        (self.root / "gen.py").write_text("import os\nfrom helper import X\n", encoding="utf-8")
        (self.root / "tools" / "helper.py").write_text("import deep\nX = 1\n", encoding="utf-8")
        self.assertEqual(regen.local_imports(self.root, "gen.py"), ("tools/deep.py", "tools/helper.py"))
        before = regen.signature(self.root, self.entry)
        (self.root / "tools" / "deep.py").write_text("Y = 22\n", encoding="utf-8")
        regen._GLOBS.clear()
        self.assertNotEqual(regen.signature(self.root, self.entry), before)

    def test_missing_dependency_skips_a_full_run_and_fails_a_named_one(self):
        entry = regen.Entry("needs", "test", ("gen.py",), None, ("gen.py",), needs=("no_such_module_xyz",))
        result = regen.regen("check", [entry], self.root, self.state, run=lambda *a: self.fail("must not run"))
        self.assertEqual((result["exit_code"], result["skipped"]), (0, ["needs"]))
