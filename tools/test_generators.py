        self.assertEqual((snapshot["region"], snapshot["artifact"]), ("region.a", "cell2"))
        self.assertEqual(snapshot["regions_done"], [])
        self.assertEqual(snapshot["eta_seconds"], 25)  # 5 s per artifact so far, 5 left
        nothing = world_bake.progress(expected, started + 100, started + 100, fallback_rate=2.0)
        self.assertEqual((nothing["done"], nothing["eta_seconds"]), (0, 14))

