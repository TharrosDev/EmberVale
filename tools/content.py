ID = re.compile(r"[a-z][a-z0-9_]*(?:\.[a-z0-9_{}]+)+")
CODE_STRING = re.compile(r'"([a-z][a-z0-9_]*(?:\.[a-z0-9_]+)+)"')
GENERATED = re.compile(r"(?im)^[;#] *generated by (tools/[\w/.]+\.py)")
LOCALE = "data/locale/strings.csv"
ARTIFACTS = ROOT / "artifacts" / "content"
CONTENT_PATHS = ("data", "scenes")
CACHE = ARTIFACTS / "index.json"
CACHE_SCHEMA = 1
#: prepared world artifacts are binary build output; tools/world_bake.py --plan reports on them.
BAKED = ":(exclude)data/world_bake"


# ------------------------------------------------------------------------------------- index

@dataclass
class Definition:
    id: str
    kind: str
    path: str
    script_class: str
    generated: str
    section: str = ""


@dataclass
class Index:
    defs: dict[str, list[Definition]] = field(default_factory=lambda: defaultdict(list))
    uses: dict[str, list[tuple[str, str, str]]] = field(default_factory=lambda: defaultdict(list))
    files: dict[str, dict] = field(default_factory=dict)
    locale: set[str] = field(default_factory=set)
    root: Path = ROOT


def kind_of(rel: str) -> str:
    parts = rel.split("/")
    if rel.endswith(".json"):
        return "json"
    if parts[0] == "data" and len(parts) > 2:
        return parts[1]
    if parts[0] == "scenes":
        return "scenes"
    if parts[0] == "src":
        return "code"
    if parts[0] == "tools":
        return "tools"
    if parts[0] == "tests":
        return "tests"
    return parts[0]


def generated_by(text: str) -> str:
    match = GENERATED.search(text[:4000])
    return match.group(1) if match else ""


def document_record(rel: str, text: str) -> dict:
    """What one .tres/.tscn defines and every id or res:// path it mentions, as plain JSON."""
    doc = tres_reader.parse(text)
    kind = kind_of(rel)
    generator = generated_by(text)
    root = doc.root
    root_id = root.get("Id") if root is not None else None
    record = {"info": {"kind": kind, "generated": generator,
                       "id": root_id if isinstance(root_id, str) else ""},
              "defs": [], "uses": []}
    if isinstance(root_id, str) and root_id:
        record["defs"].append([root_id, kind, doc.script_class, generator, ""])
    for section in doc.sections:
        if section.kind == "ext_resource":
            path = section.attrs.get("path")
            if isinstance(path, str) and path.startswith("res://"):
                record["uses"].append([path, "ext_resource"])
            continue
        own_id = section.get("Id")
        if section.kind == "sub_resource" and isinstance(own_id, str) and ID.fullmatch(own_id):
            sub_kind = "cells" if kind == "regions" and "ScenePath" in section.props else f"{kind}.sub"
            record["defs"].append([own_id, sub_kind, doc.script_class, generator, section.label])
        for key, value in section.props.items():
            if key == "Id" and (section is root or section.kind == "sub_resource"):
                continue
            for string in tres_reader.strings_in(value):
                if string.startswith("res://") or ID.fullmatch(string):
                    record["uses"].append([string, f"{section.label}.{key}"])
    return record


def code_record(rel: str, text: str) -> dict:
    uses = []
    for number, line in enumerate(text.splitlines(), 1):
        if '"' not in line:
            continue
        for match in CODE_STRING.finditer(line):
            uses.append([match.group(1), f"line {number}"])
    return {"info": None, "defs": [], "uses": uses}


def locale_keys(text: str) -> set[str]:
    keys: set[str] = set()
    for line in text.splitlines():
        if not line or line.startswith("#"):
            continue
        keys.add(line.split(",", 1)[0])
    return keys


def source_files(root: Path, code: bool) -> list[tuple[str, Path]]:
    found: list[tuple[str, Path]] = []
    for folder in CONTENT_PATHS:
        for path in sorted((root / folder).rglob("*")):
            rel = path.relative_to(root).as_posix()
            if path.suffix in (".tres", ".tscn") and path.is_file() and not rel.startswith("data/_templates/"):
                found.append((rel, path))
    if code:
        # tests and GDScript probes name ids too: a rename that misses them breaks the build or a gate.
        # So does authored JSON under data/ (the campaign graph and its specs name enemies and items).
        for folder, pattern in (("src", "*.cs"), ("tools", "*.py"), ("tools", "*.gd"), ("tests", "*.cs"),
                                ("data", "*.json")):
            for path in sorted((root / folder).rglob(pattern)):
                rel = path.relative_to(root).as_posix()
                # data/world_bake is a manifest of hashes, not content.
                if "/obj/" in rel or "/bin/" in rel or rel.startswith("data/world_bake/"):
                    continue
                if "/test_" not in rel and not rel.endswith(("tools/content.py", "tools/tres_reader.py")):
                    found.append((rel, path))
    return found


def build_index(root: Path = ROOT, code: bool = True, cache: Path | None = None) -> Index:
    """Index the tree. With `cache`, a file whose size and mtime are unchanged is not re-read."""
    cached: dict = {}
    if cache is not None and cache.is_file():
        try:
            loaded = json.loads(cache.read_text(encoding="utf-8"))
            cached = loaded["files"] if loaded.get("schema") == CACHE_SCHEMA else {}
        except (OSError, ValueError, KeyError):
            cached = {}
    index = Index(root=root)
    records: dict[str, dict] = {}
    dirty = False
    for rel, path in source_files(root, code):
        stat = path.stat()
        signature = [stat.st_size, stat.st_mtime_ns]
        record = cached.get(rel)
        if record is None or record.get("sig") != signature:
            text = path.read_text(encoding="utf-8", errors="replace")
            record = document_record(rel, text) if path.suffix in (".tres", ".tscn") else code_record(rel, text)
            record["sig"] = signature
            dirty = True
        records[rel] = record
        kind = kind_of(rel)
        if record["info"] is not None:
            index.files[rel] = record["info"]
        for token, def_kind, script_class, generator, section in record["defs"]:
            index.defs[token].append(Definition(token, def_kind, rel, script_class, generator, section))
        for token, where in record["uses"]:
            index.uses[token].append((kind, rel, where))
    locale = root / LOCALE
    if locale.is_file():
        index.locale = locale_keys(locale.read_text(encoding="utf-8", errors="replace"))
    if cache is not None:
        # A content-only build leaves the cached code records alone rather than dropping them.
        gone = [rel for rel in cached if rel not in records
                and (code or not rel.startswith(("src/", "tools/")))]
        if dirty or gone:
            cached.update(records)
            for rel in gone:
                del cached[rel]
            cache.parent.mkdir(parents=True, exist_ok=True)
            temporary = cache.with_suffix(".tmp")
            temporary.write_text(json.dumps({"schema": CACHE_SCHEMA, "files": cached}), encoding="utf-8")
            temporary.replace(cache)
    return index


# ------------------------------------------------------------------------------------- refs

def resolve_query(index: Index, query: str) -> list[str]:
    """The index tokens a query stands for: the id itself, its defining files' res:// paths, and
    for a bare stem or partial path every res:// token that ends with it."""
    tokens = [query] if query in index.defs or query in index.uses else []
    for definition in index.defs.get(query, ()):
        if not definition.section:
            tokens.append("res://" + definition.path)
    if not query.startswith("res://") and not tokens:
        stem = query.rsplit("/", 1)[-1]
        for token in index.uses:
            if not token.startswith("res://"):
                continue
            name = token.rsplit("/", 1)[-1]
            if token.endswith("/" + query) or name == stem or name.rsplit(".", 1)[0] == stem:
                tokens.append(token)
    return list(dict.fromkeys(tokens))


def refs(index: Index, query: str) -> dict:
    tokens = resolve_query(index, query)
    definitions = [vars(d) for d in index.defs.get(query, ())]
    uses: list[dict] = []
    seen: set[tuple] = set()
    for token in tokens:
        for kind, path, where in index.uses.get(token, ()):
            key = (kind, path, where)
            if key in seen:
                continue
            seen.add(key)
            uses.append({"kind": kind, "path": path, "where": where,
                         **({"via": token} if token != query else {})})
    uses.sort(key=lambda use: (use["kind"], use["path"], use["where"]))
    locale = sorted(key for key in index.locale if key == query or key.startswith(query + "."))
    return {"query": query, "defs": definitions, "uses": uses, "locale_keys": locale,
            "by_kind": dict(Counter(use["kind"] for use in uses))}


def unused(index: Index, kind: str | None) -> list[Definition]:
    out = []
    for token, definitions in sorted(index.defs.items()):
        for definition in definitions:
            if kind and definition.kind != kind:
                continue
            path_token = "res://" + definition.path
            used = any(path != definition.path for _, path, _ in index.uses.get(token, ()))
            used = used or (not definition.section and any(
                path != definition.path for _, path, _ in index.uses.get(path_token, ())))
            if not used:
                out.append(definition)
    return out


def dangling(index: Index) -> list[dict]:
    prefixes = {token.split(".", 1)[0] for token, definitions in index.defs.items()
                if any(not definition.section for definition in definitions)}
    out = []
    for token, uses in sorted(index.uses.items()):
        content_uses = [use for use in uses if use[0] not in ("code", "tools", "tests", "json")]
        if not content_uses or "{" in token:
            continue
        if token.startswith("res://"):
            target = index.root / token[len("res://"):]
            if not target.exists():
                out.append({"token": token, "why": "missing file", "uses": content_uses})
        elif (token not in index.defs and token not in index.locale
              and token.split(".", 1)[0] in prefixes):
            out.append({"token": token, "why": "undefined id", "uses": content_uses})
    return out


def cmd_refs(args) -> int:
    index = build_index(cache=CACHE)
    if args.unused:
        rows = unused(index, args.kind)
        if args.json:
            print(json.dumps({"unused": [vars(d) for d in rows]}))
        else:
            for definition in rows:
                print(f"unused  {definition.id}  {definition.kind}  {definition.path}")
            print(f"summary unused {len(rows)}" + (f" kind {args.kind}" if args.kind else ""))
        return 0
    if args.dangling:
        rows = dangling(index)
        if args.json:
            print(json.dumps({"dangling": rows}))
        else:
            for row in rows:
                kind, path, where = row["uses"][0]
                more = f"  (+{len(row['uses']) - 1} more)" if len(row["uses"]) > 1 else ""
                print(f"dangling  {row['token']}  {row['why']}  {path}  {where}{more}")
            print(f"summary dangling {len(rows)}")
        return 0
    if args.prefix is not None:
        rows = [d for token, ds in sorted(index.defs.items()) if token.startswith(args.prefix)
                for d in ds if not args.kind or d.kind == args.kind]
        if args.json:
            print(json.dumps({"defs": [vars(d) for d in rows]}))
        else:
            shown_rows = rows if args.limit is None else rows[:args.limit]
            for definition in shown_rows:
                print(f"def  {definition.id}  {definition.kind}  {definition.path}")
            if len(shown_rows) < len(rows):
                print(f"def  ... {len(rows) - len(shown_rows)} more (raise --limit)")
            print(f"summary defs {len(rows)}")
        return 0
    if not args.id:
        print("refs: give an id, a res:// path or a model stem, or --unused/--dangling/--prefix",
              file=sys.stderr)
        return 2
    result = refs(index, args.id)
    limit = 25 if args.limit is None else args.limit
    if args.json:
        print(json.dumps(result))
    else:
        for definition in result["defs"]:
            where = f"#{definition['section']}" if definition["section"] else ""
            generated = f"  generated:{definition['generated']}" if definition["generated"] else ""
            print(f"def  {definition['id']}  {definition['kind']}  {definition['path']}{where}"
                  f"  {definition['script_class']}{generated}")
        shown: Counter = Counter()
        for use in result["uses"]:
            shown[use["kind"]] += 1
            if shown[use["kind"]] > limit:
                continue
            via = f"  via {use['via']}" if "via" in use else ""
            print(f"use  {use['kind']}  {use['path']}  {use['where']}{via}")
        for kind, count in sorted(shown.items()):
            if count > limit:
                print(f"use  {kind}  ... {count - limit} more (raise --limit)")
        if result["locale_keys"]:
            keys = result["locale_keys"]
            print(f"locale  {len(keys)} key(s): {', '.join(keys[:4])}{' ...' if len(keys) > 4 else ''}")
        kinds = ", ".join(f"{kind} {count}" for kind, count in sorted(result["by_kind"].items()))
        print(f"summary {args.id}  defs {len(result['defs'])}  uses {len(result['uses'])}"
              + (f"  ({kinds})" if kinds else ""))
    return 0 if result["defs"] or result["uses"] else 1


# ------------------------------------------------------------------------------------- census

def census(root: Path = ROOT, cache: Path | None = None) -> dict:
    index = build_index(root, code=False, cache=cache)
    kinds: dict[str, dict] = {}
    for rel, info in sorted(index.files.items()):
        if not rel.startswith("data/"):
            continue
        row = kinds.setdefault(info["kind"], {"files": 0, "generated": 0, "hand": 0})
        row["files"] += 1
        row["generated" if info["generated"] else "hand"] += 1
    cells: Counter = Counter()
    for definitions in index.defs.values():
        for definition in definitions:
            if definition.kind == "cells":
                cells[definition.path.rsplit("/", 1)[-1].removesuffix(".tres")] += 1
    bosses = 0
    for rel in index.files:
        if rel.startswith("data/enemies/"):
            doc = tres_reader.load(root / rel)
            bosses += 1 if doc.root is not None and doc.root.get("IsBoss") is True else 0
    return {
        "kinds": kinds,
        "cells": dict(sorted(cells.items())),
        "cells_total": sum(cells.values()),
        "scenes": sum(1 for rel in index.files if rel.startswith("scenes/")),
        "locale_rows": len(index.locale),
        "bosses": bosses,
        "main_quests": sum(1 for token in index.defs if token.startswith("quest.main.")),
        "ids": sum(len(v) for v in index.defs.values()),
    }


def cmd_census(args) -> int:
    result = census(cache=CACHE)
    if args.json:
        print(json.dumps(result))
        return 0
    for kind, row in result["kinds"].items():
        extra = ""
        if kind == "enemies":
            extra = f", bosses {result['bosses']}"
        elif kind == "quests":
            extra = f", main {result['main_quests']}"
        print(f"{kind:<16} {row['files']:>4}  (generated {row['generated']}, hand {row['hand']}{extra})")
    regions = ", ".join(f"{name} {count}" for name, count in result["cells"].items())
    print(f"{'cells':<16} {result['cells_total']:>4}  ({regions})")
    print(f"{'scenes':<16} {result['scenes']:>4}")
    print(f"{'locale rows':<16} {result['locale_rows']:>4}")
    print(f"summary ids {result['ids']}  data files {sum(r['files'] for r in result['kinds'].values())}")
    return 0


# ------------------------------------------------------------------------------------- diff

def git(*arguments: str, data: bytes | None = None) -> bytes:
    return subprocess.run(["git", *arguments], cwd=ROOT, input=data, capture_output=True, check=True).stdout


def git_blobs(revision: str, paths: list[str]) -> dict[str, str | None]:
    """Many files at one revision through a single `git cat-file --batch` process."""
    if not paths:
        return {}
    request = "".join(f"{revision}:{path}\n" for path in paths).encode("utf-8")
    stream = io.BytesIO(git("cat-file", "--batch", data=request))
    out: dict[str, str | None] = {}
    for path in paths:
        header = stream.readline().decode("utf-8", "replace").strip()
        if header.endswith("missing") or not header:
            out[path] = None
            continue
        size = int(header.rsplit(" ", 1)[-1])
        out[path] = stream.read(size).decode("utf-8", "replace")
        stream.read(1)
    return out


def changed_paths(rev_a: str, rev_b: str | None) -> list[tuple[str, str]]:
    arguments = ["diff", "--name-status", "--no-renames", "-z", rev_a]
    if rev_b:
        arguments.append(rev_b)
    names = git(*arguments, "--", *CONTENT_PATHS, BAKED).decode("utf-8", "replace").split("\0")
    changes = [(names[i], names[i + 1]) for i in range(0, len(names) - 1, 2)]
    if not rev_b:
        untracked = git("ls-files", "--others", "--exclude-standard", "-z", "--", *CONTENT_PATHS)
        changes += [("A", name) for name in untracked.decode("utf-8", "replace").split("\0") if name]
    return changes


def flatten(doc: tres_reader.Doc) -> dict[str, object]:
    flat: dict[str, object] = {}
    for section in doc.sections:
        if section.kind == "resource":
            prefix = ""
        elif section.kind in ("sub_resource", "node"):
            prefix = section.label + "."
        else:
            continue
        for key, value in section.props.items():
            if key != "script":
                flat[prefix + key] = value
    return flat


def short(value) -> str:
    if isinstance(value, Ref):
        return f"{value.kind}:{value.id}"
    if isinstance(value, float):
        return f"{value:g}"
    if isinstance(value, list):
        return f"[{len(value)}]" if len(value) > 3 else "[" + ", ".join(short(v) for v in value) + "]"
    text = str(value)
    return text if len(text) <= 40 else text[:37] + "..."


def diff_documents(old: str | None, new: str | None) -> dict:
    """Field-level difference of two versions of one .tres/.tscn (either side may be absent)."""
    old_flat = flatten(tres_reader.parse(old)) if old is not None else {}
    new_flat = flatten(tres_reader.parse(new)) if new is not None else {}
    fields = []
    for key in sorted(set(old_flat) | set(new_flat)):
        before, after = old_flat.get(key), new_flat.get(key)
        if before != after:
            fields.append({"field": key,
                           "old": None if key not in old_flat else short(before),
                           "new": None if key not in new_flat else short(after)})
    return {"fields": fields}


def diff_locale(old: str | None, new: str | None) -> dict:
    def rows(text):
        out = {}
        for line in (text or "").splitlines():
            if line and not line.startswith("#"):
                key, _, rest = line.partition(",")
                out[key] = rest
        return out
    before, after = rows(old), rows(new)
    return {"added": len(set(after) - set(before)), "removed": len(set(before) - set(after)),
            "changed": sum(1 for key in set(before) & set(after) if before[key] != after[key])}


def root_id(text: str | None) -> str:
    if text is None:
        return ""
    doc = tres_reader.parse(text)
    value = doc.root.get("Id") if doc.root is not None else None
    return value if isinstance(value, str) else ""


def content_diff(rev_a: str, rev_b: str | None, kind_filter: str | None = None) -> dict:
    changes = changed_paths(rev_a, rev_b)
    paths = [path for _, path in changes]
    old = git_blobs(rev_a, paths)
    if rev_b:
        new = git_blobs(rev_b, paths)
    else:
        new = {}
        for path in paths:
            target = ROOT / path
            new[path] = target.read_text(encoding="utf-8", errors="replace") if target.is_file() else None
    facts = []
    for status, path in changes:
        kind = kind_of(path)
        if kind_filter and kind != kind_filter:
            continue
        before, after = old.get(path), new.get(path)
        fact = {"status": {"A": "+", "D": "-"}.get(status, "~"), "kind": kind, "path": path}
        if path == LOCALE:
            fact.update(kind="locale", locale=diff_locale(before, after))
        elif path.endswith((".tres", ".tscn")):
            fact["id"] = root_id(after) or root_id(before)
            if fact["status"] == "~":
                fact.update(diff_documents(before, after))
                if not fact["fields"]:
                    continue  # comments, ordering or line endings only
        facts.append(fact)
    summary: dict[str, Counter] = defaultdict(Counter)
    for fact in facts:
        summary[fact["kind"]][fact["status"]] += 1
    return {"a": rev_a, "b": rev_b or "worktree", "facts": facts,
            "summary": {kind: dict(counts) for kind, counts in sorted(summary.items())}}


def fact_line(fact: dict, fields: bool) -> str:
    name = fact.get("id") or fact["path"]
    line = f"{fact['status']} {name} ({fact['kind']})"
    if "locale" in fact:
        counts = fact["locale"]
        return f"~ locale keys +{counts['added']} -{counts['removed']} ~{counts['changed']}"
    changed = fact.get("fields") or []
    if not changed:
        return line
    sections = sorted({f["field"].rsplit(".", 1)[0] for f in changed if "." in f["field"]})
    if len(changed) > 6 and not fields:
        tail = f" in {len(sections)} section(s): {', '.join(sections[:3])}" if sections else ""
        return f"{line} {len(changed)} fields{tail}{' ...' if len(sections) > 3 else ''}"
    parts = [f"{f['field']} {f['old'] if f['old'] is not None else '(unset)'} -> "
             f"{f['new'] if f['new'] is not None else '(unset)'}" for f in changed]
    return f"{line} " + "; ".join(parts)


def summary_line(summary: dict) -> str:
    parts = []
    for kind, counts in summary.items():
        parts.append(kind + " " + " ".join(f"{sign}{counts[sign]}" for sign in "+~-" if counts.get(sign)))
    return "summary " + (" | ".join(parts) if parts else "no content changes")


def cmd_diff(args) -> int:
    try:
        result = content_diff(args.rev_a, args.rev_b, args.kind)
    except subprocess.CalledProcessError as error:
        print(f"diff: git failed: {error.stderr.decode('utf-8', 'replace').strip()}", file=sys.stderr)
        return 2
    safe = lambda rev: re.sub(r"[^A-Za-z0-9_.-]", "_", rev)[:40]
    report = ARTIFACTS / f"diff-{safe(result['a'])}-{safe(result['b'])}.json"
    write_json(report, result)
    if args.json:
        print(json.dumps({**result, "report": report.relative_to(ROOT).as_posix()}))
        return 0
    lines = [fact_line(fact, args.fields) for fact in result["facts"]]
    if len(lines) > args.max_lines and not args.fields:
        print(f"{len(lines)} changes; showing counts (use --kind K, --fields or --max-lines N for lines)")
    else:
        for line in lines:
            print(line)
    print(summary_line(result["summary"]))
    print(f"report {report.relative_to(ROOT).as_posix()}")
    return 0


