COMBAT_MATH = "src/Combat/CombatMath.cs"
POWER_SCALING = 0.5
#: source text that must still be present in CombatMath.cs for the mirror below to be trusted.
COMBAT_MATH_ANCHORS = (
    "private const float PowerScaling = 0.5f;",
    "return baseDamage + (power * scaling);",
    "return 100f / (100f + clamped);",
)
ARMOUR_SLOTS = (3, 4, 5, 6, 7)  # EquipmentSlot Head, Chest, Hands, Legs, Feet
MAIN_HAND = 1


def combat_math_drift(root: Path = ROOT) -> list[str]:
    text = (root / COMBAT_MATH).read_text(encoding="utf-8", errors="replace")
    return [anchor for anchor in COMBAT_MATH_ANCHORS if anchor not in text]


def armor_multiplier(armor: float) -> float:
    return 100.0 / (100.0 + max(0.0, armor))


def scale_damage(base: float, power: float, scaling: float = POWER_SCALING) -> float:
    return base + power * scaling


def hits_to_kill(health: float, base: float, power: float, armor: float) -> float:
    hit = max(1.0, scale_damage(base, power) * armor_multiplier(armor))
    return health / hit


def xp_to_leave(level: int, base_xp: float, exponent: float, max_level: int) -> int:
    return 0 if level >= max_level else int(round(base_xp * level ** exponent))


def number(section, key: str, default: float = 0.0) -> float:
    value = section.get(key, default) if section is not None else default
    return float(value) if isinstance(value, (int, float)) and not isinstance(value, bool) else default


def res_path(root: Path, value) -> Path | None:
    return root / value[len("res://"):] if isinstance(value, str) and value.startswith("res://") else None


def load_root(path: Path | None):
    if path is None or not path.is_file():
        return None
    return tres_reader.load(path).root


def tier_tables() -> tuple[dict, dict]:
    sys.path.insert(0, str(ROOT / "tools" / "items"))
    try:
        import catalogue  # the generators' own source of truth for tier -> realm and level band
    finally:
        sys.path.pop(0)
    return dict(catalogue.TIER_LEVELS), dict(catalogue.TIER_REGION)


def median(values: list[float]) -> float:
    return statistics.median(values) if values else 0.0


def tier_kits(root: Path = ROOT) -> dict[int, dict]:
    """A typical on-tier kit: the median main-hand weapon and the median armour piece per slot."""
    weapons: dict[int, list[tuple[float, float]]] = defaultdict(list)
    armour: dict[int, dict[int, list[tuple[float, float]]]] = defaultdict(lambda: defaultdict(list))
    for path in sorted((root / "data" / "items").glob("*.tres")):
        doc = tres_reader.load(path)
        item = doc.root
        if item is None or not isinstance(item.get("Tier"), int) or not item.get("Slot"):
            continue
        tier, slot = item.get("Tier"), item.get("Slot")
        if slot == MAIN_HAND:
            weapon = load_root(res_path(root, doc.resolve(item.get("Weapon"))))
            if weapon is not None:
                weapons[tier].append((number(weapon, "BaseDamage"), number(item, "BonusPhysicalPower")))
        elif slot in ARMOUR_SLOTS:
            armour[tier][slot].append((number(item, "BonusArmor"), number(item, "BonusMaxHealth")))
    kits = {}
    for tier in sorted(set(weapons) | set(armour)):
        kits[tier] = {
            "weapon_damage": median([w[0] for w in weapons[tier]]),
            "power": median([w[1] for w in weapons[tier]]),
            "armor": sum(median([a[0] for a in armour[tier][slot]]) for slot in ARMOUR_SLOTS),
            "health": sum(median([a[1] for a in armour[tier][slot]]) for slot in ARMOUR_SLOTS),
        }
    return kits


def player_at(level: int, kit: dict, base, progression) -> dict:
    grown = level - 1
    return {
        "health": number(base, "Health") + number(progression, "HealthPerLevel") * grown + kit["health"],
        "power": number(base, "PhysicalPower") + number(progression, "PhysicalPowerPerLevel") * grown + kit["power"],
        "armor": number(base, "Armor") + number(progression, "ArmorPerLevel") * grown + kit["armor"],
        "weapon_damage": kit["weapon_damage"],
    }


def enemy_regions(index: Index, enemy_id: str, folders: dict[str, str]) -> tuple[set[str], bool]:
    """(regions an enemy is tied to, whether an encounter can also bring it anywhere).

    Sources: an encounter's RegionIds, and any region scene that names the enemy or names a
    resource (boss, encounter) that names it."""
    regions: set[str] = set()
    anywhere = False
    tokens = [enemy_id]
    for kind, path, _ in index.uses.get(enemy_id, ()):
        if kind == "encounters":
            root = tres_reader.load(index.root / path).root
            listed = [r for r in (root.get("RegionIds") or []) if isinstance(r, str)] if root else []
            regions.update(listed)
            anywhere = anywhere or not listed
        owner = index.files.get(path, {}).get("id")
        if owner and kind in ("bosses", "encounters"):
            tokens.append(owner)
    for token in tokens:
        for kind, path, _ in index.uses.get(token, ()):
            parts = path.split("/")
            if kind == "scenes" and len(parts) > 3 and parts[1] == "regions" and parts[2] in folders:
                regions.add(folders[parts[2]])
    return regions, anywhere


def region_folders(root: Path = ROOT) -> dict[str, str]:
    """scenes/regions/<folder> -> region id, read from each region resource's cell scene paths."""
    folders: dict[str, str] = {}
    for path in sorted((root / "data" / "regions").glob("*.tres")):
        text = path.read_text(encoding="utf-8", errors="replace")
        region = re.search(r'^Id = "(region\.[^"]+)"', text, re.MULTILINE)
        if region:
            for folder in set(re.findall(r'res://scenes/regions/([^/"]+)/', text)):
                folders[folder] = region.group(1)
    return folders


def balance_enemies(root: Path = ROOT, index: Index | None = None) -> list[dict]:
    index = index or build_index(root, code=False, cache=CACHE if root == ROOT else None)
    tier_levels, tier_region = tier_tables()
    region_tier = {region: tier for tier, region in tier_region.items()}
    folders = region_folders(root)
    kits = tier_kits(root)
    base = load_root(root / "data" / "attributes" / "PlayerAttributes.tres")
    progression = load_root(root / "data" / "progression" / "PlayerProgression.tres")
    empty_kit = {"weapon_damage": 0.0, "power": 0.0, "armor": 0.0, "health": 0.0}
    rows = []
    for path in sorted((root / "data" / "enemies").glob("*.tres")):
        enemy = tres_reader.load(path).root
        if enemy is None or not isinstance(enemy.get("Id"), str):
            continue
        attributes = load_root(res_path(root, enemy.get("AttributesPath")))
        weapon = load_root(res_path(root, enemy.get("WeaponPath")))
        regions, anywhere = enemy_regions(index, enemy.get("Id"), folders)
        tiers = sorted(region_tier[r] for r in regions if r in region_tier)
        known = bool(tiers) or anywhere
        if anywhere or not tiers:
            tiers = sorted(set(tiers) | {min(tier_levels)}) if anywhere else sorted(tier_levels)
        low_tier, high_tier = tiers[0], tiers[-1]
        low_level, high_level = tier_levels[low_tier][0], tier_levels[high_tier][1]
        health, armor = number(attributes, "Health"), number(attributes, "Armor")
        enemy_base, enemy_power = number(weapon, "BaseDamage"), number(attributes, "PhysicalPower")
        row = {"id": enemy.get("Id"), "boss": enemy.get("IsBoss") is True,
               "tiers": tiers, "band_known": known, "levels": [low_level, high_level],
               "hp": health, "armor": armor, "xp": number(enemy, "XpValue"),
               "xp_per_hp": round(number(enemy, "XpValue") / health, 3) if health else 0.0}
        for edge, tier, level in (("lo", low_tier, low_level), ("hi", high_tier, high_level)):
            player = player_at(level, kits.get(tier, empty_kit), base, progression)
            row[f"ttk_{edge}"] = round(hits_to_kill(health, player["weapon_damage"], player["power"], armor), 1)
            row[f"ttd_{edge}"] = round(hits_to_kill(player["health"], enemy_base, enemy_power, player["armor"]), 1)
        rows.append(row)
    flag_enemies(rows)
    return rows


def flag_enemies(rows: list[dict]) -> None:
    """Outlier flags, each relative to the ordinary enemies that share the row's lowest tier."""
    by_tier: dict[int, list[dict]] = defaultdict(list)
    for row in rows:
        if not row["boss"] and row["band_known"]:
            by_tier[row["tiers"][0]].append(row)
    for row in rows:
        flags = []
        peers = by_tier.get(row["tiers"][0], [])
        if not row["band_known"]:
            flags.append("band-unknown")
        if row["ttd_lo"] < 2.0:
            flags.append("one-shots-at-entry")
        if peers and not row["boss"]:
            typical = median([peer["ttk_lo"] for peer in peers])
            if typical and row["ttk_lo"] > 3 * typical:
                flags.append("tanky")
            if typical and row["ttk_lo"] < typical / 3:
                flags.append("fragile")
            typical_xp = median([peer["xp_per_hp"] for peer in peers])
            if typical_xp and not typical_xp / 3 <= row["xp_per_hp"] <= typical_xp * 3:
                flags.append("xp-outlier")
        if peers and row["boss"] and row["hp"] < max(peer["hp"] for peer in peers):
            flags.append("boss-weaker-than-trash")
        row["flags"] = flags


def item_values(root: Path = ROOT) -> dict[str, float]:
    values = {}
    for path in sorted((root / "data" / "items").glob("*.tres")):
        item = tres_reader.load(path).root
        if item is not None and isinstance(item.get("Id"), str):
            values[item.get("Id")] = number(item, "Value")
    return values


def table_value(root: Path, path: Path | None, values: dict[str, float], tier: int, depth: int = 0) -> float:
    """Expected sale value of one roll of a loot table. Ungrouped entries roll independently; the
    entries of one Group are treated as one weighted pick. An estimate: level and rarity gates,
    affixes and once-per-save rows are ignored."""
    if path is None or not path.is_file() or depth > 3:
        return 0.0
    doc = tres_reader.load(path)
    table = doc.root
    if table is None:
        return 0.0
    total = number(table, "GoldChance") * (number(table, "GoldMin") + number(table, "GoldMax")) / 2
    groups: dict[str, list[tuple[float, float]]] = defaultdict(list)
    for entry in doc.resolve(table.get("Entries") or []):
        if not isinstance(entry, tres_reader.Section):
            continue
        quantity = (number(entry, "MinQuantity", 1) + number(entry, "MaxQuantity", 1)) / 2
        nested = entry.get("TablePath")
        if isinstance(nested, str) and nested:
            worth = table_value(root, res_path(root, nested.replace("{tier}", str(tier))), values, tier, depth + 1)
        else:
            worth = values.get(entry.get("ItemId"), 0.0) * quantity
        expected = number(entry, "DropChance", 1.0) * worth
        group = entry.get("Group")
        if isinstance(group, str) and group:
            groups[group].append((number(entry, "Weight", 1.0), expected))
        else:
            total += expected
    for picks in groups.values():
        weight = sum(w for w, _ in picks)
        total += sum(w * v for w, v in picks) / weight if weight else 0.0
    return total


def balance_loot(root: Path = ROOT, enemies: list[dict] | None = None) -> list[dict]:
    enemies = enemies if enemies is not None else balance_enemies(root)
    tiers = {row["id"]: row for row in enemies}
    values = item_values(root)
    rows = []
    for path in sorted((root / "data" / "enemies").glob("*.tres")):
        enemy = tres_reader.load(path).root
        if enemy is None or enemy.get("Id") not in tiers:
            continue
        info = tiers[enemy.get("Id")]
        tier = info["tiers"][0]
        value = table_value(root, res_path(root, enemy.get("LootTablePath")), values, tier)
        xp = info["xp"]
        rows.append({"id": info["id"], "tier": tier, "boss": info["boss"], "value_per_kill": round(value, 1),
                     "xp": xp, "value_per_100xp": round(100 * value / xp, 1) if xp else 0.0, "flags": []})
    by_tier: dict[int, list[float]] = defaultdict(list)
    for row in rows:
        if not row["boss"]:
            by_tier[row["tier"]].append(row["value_per_100xp"])
    for row in rows:
        typical = median(by_tier.get(row["tier"], []))
        if row["value_per_kill"] == 0:
            row["flags"].append("drops-nothing")
        elif typical and not row["boss"] and not typical / 3 <= row["value_per_100xp"] <= typical * 3:
            row["flags"].append("value-outlier")
    return rows


def balance_recipes(root: Path = ROOT) -> list[dict]:
    """Ingredient cost against output worth at base item Value (no shop spread, no standing).
    tools/gen_recipes.py --report is the shop-priced commission table."""
    values = item_values(root)
    rows = []
    for path in sorted((root / "data" / "recipes").glob("*.tres")):
        doc = tres_reader.load(path)
        recipe = doc.root
        if recipe is None or not isinstance(recipe.get("Id"), str):
            continue
        cost, missing = 0.0, []
        for ingredient in doc.resolve(recipe.get("Ingredients") or []):
            if not isinstance(ingredient, tres_reader.Section):
                continue
            item = ingredient.get("ItemId")
            if item not in values:
                missing.append(str(item))
            cost += values.get(item, 0.0) * number(ingredient, "Quantity", 1)
        output = recipe.get("OutputItemId")
        worth = values.get(output, 0.0) * number(recipe, "OutputQuantity", 1)
        flags = []
        if missing or output not in values:
            flags.append("missing-item")
        if cost and worth / cost > 3:
            flags.append("output-worth-3x-cost")
        if cost and worth and worth / cost < 1 / 3:
            flags.append("output-under-third-of-cost")
        rows.append({"id": recipe.get("Id"), "tier": recipe.get("Tier", 0), "cost": round(cost, 1),
                     "worth": round(worth, 1), "ratio": round(worth / cost, 2) if cost else 0.0,
                     "flags": flags})
    return rows


def balance_xp(root: Path = ROOT, enemies: list[dict] | None = None) -> list[dict]:
    enemies = enemies if enemies is not None else balance_enemies(root)
    tier_levels, _ = tier_tables()
    progression = load_root(root / "data" / "progression" / "PlayerProgression.tres")
    base_xp, exponent = number(progression, "BaseXpToLevel", 100), number(progression, "XpCurveExponent", 1.5)
    max_level = int(number(progression, "MaxLevel", 50))
    rows = []
    for tier, (low, high) in sorted(tier_levels.items()):
        needed = sum(xp_to_leave(level, base_xp, exponent, max_level) for level in range(low, high))
        ordinary = [row["xp"] for row in enemies
                    if not row["boss"] and row["band_known"] and tier in row["tiers"] and row["xp"]]
        typical = median(ordinary)
        kills = round(needed / typical) if typical else 0
        flags = [] if ordinary else ["no-enemies"]
        rows.append({"id": f"tier{tier}", "tier": tier, "levels": [low, high], "xp_needed": needed,
                     "enemies": len(ordinary), "median_xp": typical, "kills_to_clear_band": kills,
                     "flags": flags})
    return rows


BALANCE = {
    "enemies": (balance_enemies, ("id", "tiers", "levels", "hp", "armor", "ttk_lo", "ttk_hi", "ttd_lo",
                                  "ttd_hi", "xp", "xp_per_hp")),
    "loot": (balance_loot, ("id", "tier", "value_per_kill", "xp", "value_per_100xp")),
    "recipes": (balance_recipes, ("id", "tier", "cost", "worth", "ratio")),
    "xp": (balance_xp, ("id", "levels", "xp_needed", "enemies", "median_xp", "kills_to_clear_band")),
}


def moved(rows: list[dict], baseline: list[dict], threshold: float) -> list[dict]:
    """Rows that are new, gone, or have a number that moved by more than `threshold` (a fraction)."""
    before = {row["id"]: row for row in baseline}
    out = []
    for row in rows:
        old = before.pop(row["id"], None)
        if old is None:
            out.append({**row, "change": "new"})
            continue
        changes = []
        for key, value in row.items():
            previous = old.get(key)
            if isinstance(value, bool) or not isinstance(value, (int, float)) or not isinstance(previous, (int, float)):
                continue
            scale = max(abs(previous), 1e-9)
            if abs(value - previous) / scale > threshold:
                changes.append(f"{key} {previous:g} -> {value:g}")
        if changes:
            out.append({**row, "change": "; ".join(changes)})
    out.extend({**row, "change": "removed"} for row in before.values())
    return out


def cell(value, column: str = "") -> str:
    if isinstance(value, list):
        return ("T" + ",".join(str(v) for v in value)) if column == "tiers" else "-".join(str(v) for v in value)
    if isinstance(value, float):
        return f"{value:g}"
    return str(value)


def cmd_balance(args) -> int:
    drift = combat_math_drift()
    if drift:
        print(f"balance: {COMBAT_MATH} changed; update the mirror in tools/content.py. Missing: "
              + " | ".join(drift), file=sys.stderr)
        return 2
    build, columns = BALANCE[args.table]
    rows = build()
    if args.save:
        write_json(Path(args.save), rows)
    if args.baseline:
        try:
            baseline = json.loads(Path(args.baseline).read_text(encoding="utf-8"))
        except (OSError, json.JSONDecodeError) as error:
            print(f"balance: cannot read baseline: {error}", file=sys.stderr)
            return 2
        rows = moved(rows, baseline, args.threshold)
        columns = ("id", "change")
    elif args.flagged:
        rows = [row for row in rows if row["flags"]]
    if args.json:
        print(json.dumps({"table": args.table, "rows": rows}))
        return 0
    print("# " + "  ".join(columns) + ("" if args.baseline else "  flags"))
    for row in rows:
        line = "  ".join(cell(row.get(column, ""), column) for column in columns)
        if not args.baseline:
            line += "  " + (",".join(row["flags"]) or "-")
        print(line)
    flagged = sum(1 for row in rows if row.get("flags"))
    print(f"summary {args.table} rows {len(rows)}"
          + (f" moved over {args.threshold:g}" if args.baseline else f" flagged {flagged}")
          + "  (estimate; see --help for what it leaves out)")
    return 0


