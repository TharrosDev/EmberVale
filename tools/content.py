#!/usr/bin/env python3
"""Engine-free questions about authored content. No Godot, no build; about a second or two.

    python tools/content.py refs item.material.scrap        who defines and who uses this id
    python tools/content.py refs enm_bandit                 ... or a model stem / res:// path
    python tools/content.py refs --prefix item.material.    list defined ids
    python tools/content.py refs --unused --kind items      defined ids nothing refers to
    python tools/content.py refs --dangling                 ids and res:// paths used but not defined
    python tools/content.py census                          what exists, per data folder
    python tools/content.py diff main                       what content changed since a commit
    python tools/content.py diff v1 v2 --kind items --fields
    python tools/content.py balance enemies|loot|recipes|xp   estimate tables with outlier flags
    python tools/content.py balance enemies --save a.json   then, after a retune:
    python tools/content.py balance enemies --baseline a.json --threshold 0.15

Every command takes --json (one object on stdout). Through the SDK:
    python tools/embervale.py tool content -- refs item.material.scrap

These are reports, never gates: ContentValidator (--validate) stays the authority on what is valid.
An "id" here is any quoted string shaped like `word.word`; a string counts as a reference only when
it equals a defined id (or, under --dangling, shares a prefix with defined ids and is not a locale
key). `balance` mirrors three formulas from src/Combat/CombatMath.cs and refuses to run when their
constants change; it ignores perks, hit zones, blocking, status effects, spells and per-attack
multipliers, so it finds outliers and does not prove a fight is winnable.
"""

