#!/usr/bin/env python3
"""Author the planned recipes (ics crafting lane) from tools/items/catalogue.py.

One table, catalogue.PLANNED_RECIPES, generates four things that MUST agree, so they cannot drift:

  1. data/recipes/<Name>.tres            one CraftingRecipeResource per planned recipe
  2. data/locale/strings.csv             <recipe id>.name for EVERY recipe (the 15 hand-authored ones
                                         included), inside '# --- BEGIN ics:crafting:recipes ---'
  3. data/services/EmberCrownTrainer.tres   its TaughtRecipeIds line
  4. (checked, not written) src/Core/GameIds.cs   Recipes.Starting must seed exactly the old list
                                         plus every recipe whose discovery is "known"

The 15 recipes main already ships are hand-authored and are NEVER written: the generator reads them
(for their names, and for the commission check) and leaves the files alone.

Discovery, as the game can express it today
-------------------------------------------
ContentValidator.ValidateRecipeReachability accepts two routes only: GameIds.Recipes.Starting, or a
ServiceKind.Trainer that lists the recipe (never both). So:
  "known"    -> Recipes.Starting
  "trainer"  -> the Ember Crown trainer's list
  "scroll"   -> the Ember Crown trainer's list AS WELL, and the recipe's ScrollItemId names the
                item.recipe_scroll.* that also teaches it (CraftingComponent.StudyScroll)
A recipe above tier 1 additionally needs a crafting rank before the player's own hands can make it
(CraftingSkill.RequiredRank), so knowing a recipe and being able to craft it are separate gates.

The commission check
--------------------
ContentValidator.ValidateCommission fails --validate when "buy every material from the master, have
him make the piece, sell it" pays for itself. No lane can run --validate, so --check restates that
inequality here from the same data: the service's labour at Allied standing with the best perk, each
ingredient at the master's cheapest counter price, the output at the keenest buyer's best day. Item
values come from data/items/*.tres; an item the content lane has not generated yet is priced from
PRICE_GUIDE (and listed as such), so the check stays meaningful before and after the merge.

Enum ordinals are read from the C# sources (a .tres stores an enum as its index).

Idempotent. Usage:  python tools/gen_recipes.py [--check] [--report]
        --check   exits 1 if anything would change or any rule fails, without writing
        --report  also prints the commission table (cost, best sale, the highest safe output value)
"""

